#!/usr/bin/env python3
"""Generate local_rules.xml (docs/wazuh-tuning/plan.md Phase 1d) from docker_healthchecks.json.

Each entry is the exact command a container's HEALTHCHECK runs; docker-listener reports it as
rule 87907 (a level-3 alert, 90% of all alert volume). One level-0 child rule per entry
suppresses exactly that command: the whole value is anchored (^exec_start: <command>\\z), so an
exec that merely contains or ends with a health-check string still alerts. The one token
<REDISPW> stands for "any non-space string" so the nextcloud Redis password never enters the repo.

    python3 gen_local_rules.py > local_rules.xml        (unit test checks the file is current)
"""
import json
import os
import re
import sys
from xml.sax.saxutils import escape

HERE = os.path.dirname(os.path.abspath(__file__))
FIRST_ID = 100100
STOCK = """<!-- Local rules -->

<!-- Modify it at your will. -->
<!-- Copyright (C) 2015, Wazuh Inc. -->

<!-- Example -->
<group name="local,syslog,sshd,">

  <!--
  Dec 10 01:02:02 host sshd[1234]: Failed none for root from 1.1.1.1 port 1066 ssh2
  -->
  <rule id="100001" level="5">
    <if_sid>5716</if_sid>
    <srcip>1.1.1.1</srcip>
    <description>sshd: authentication failed from IP 1.1.1.1.</description>
    <group>authentication_failed,pci_dss_10.2.4,pci_dss_10.2.5,</group>
  </rule>

</group>
"""


def load():
    return json.load(open(os.path.join(HERE, "docker_healthchecks.json")))


def pattern(command):
    """PCRE2 for one entry: fully anchored, literal except the password token."""
    parts = [re.escape(p) for p in command.split("<REDISPW>")]
    return "^exec_start: " + r"\S+".join(parts) + r"\z"


def render():
    out = [STOCK, '<!-- Phase 1d: docker health-check exec events (rule 87907) are not security events.',
           '     Generated by gen_local_rules.py from docker_healthchecks.json; do not edit by hand. -->',
           '<group name="local,docker,healthcheck,">']
    for i, e in enumerate(load()):
        out.append(f'  <rule id="{FIRST_ID + i}" level="0">\n    <if_sid>87907</if_sid>\n'
                   f'    <field name="docker.Action" type="pcre2">{escape(pattern(e["command"]))}</field>\n'
                   f'    <description>Docker health check (suppressed): {escape(e["container"])}</description>\n  </rule>')
    out.append("</group>\n")
    return "\n".join(out)


if __name__ == "__main__":
    sys.stdout.write(render())
